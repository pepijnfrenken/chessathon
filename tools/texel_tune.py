def format_params(p: np.ndarray) -> str:
    p = np.rint(p).astype(np.int64)
    lines = ["TUNED_PARAMS = np.array(["]
    for i in range(0, N_P, 12):
        lines.append("    " + ", ".join(f"{int(v):6d}" for v in p[i:i + 12])
                     + ",")
    lines.append("], dtype=np.int32)")
    return "\n".join(lines)


def patch_eval_py(p: np.ndarray) -> str:
    path = _HERE.parent / "engine" / "eval.py"
    src = path.read_text()
    start = src.index("# >>> TUNED_PARAMS_BLOCK >>>")
    end = src.index("# <<< TUNED_PARAMS_BLOCK <<<")
    marker_end = src.index("\n", start) + 1
    new = src[:marker_end] + format_params(p) + "\n" + src[end:]
    path.write_text(new)
    return str(path)


