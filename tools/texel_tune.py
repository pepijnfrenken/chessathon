"""Texel tuning for the phase-2 evaluation (dev tool, NOT shipped).

Fits all 813 EVAL_PARAMS of engine/eval.py to self-play positions
(generated by tools/gen_positions.py) by iteratively reweighted least
squares on Texel's logistic loss:

    L = mean((sigma(s_i) - y_i)^2),   sigma(s) = 1/(1 + 10^(-s/400)),
    s_i = score of position i (White's POV, mg/eg tapered EXACTLY as
    engine/eval.py computes it), y_i = game result from White's POV.

The eval is linear in p (score = p . f with features f re-derived here to
BIT PARITY with the jitted evaluate(); the parity is verified on random
positions before anything is fitted). Each IRWLS iteration is a weighted
least-squares solve on the 813x813 normal system, accumulated in numpy
chunks (no scipy):  p += solve(G + lam*I, b), with backtracking so the
training loss never increases.

Fitted int32 weights are patched into engine/eval.py's TUNED_PARAMS marker
block (the "tuned" config default, so agent.py and SPRT side "tuned" pick
them up unchanged) and a .npy copy is written next to the data for
provenance. Both are OUR data — generated and fitted in this repo during
this event (ORIGINALITY.md: training data unrestricted; shipped weights
must be self-trained — these are).

Usage:
    python tools/gen_positions.py --target 60000 --workers 4 --budget-ms 40
    python tools/texel_tune.py --data data/positions_<ts>.npz \
        --max-pos 50000 [--init hand|tuned] [--no-patch]
"""

