N_P = E.N_PARAMS
# Term-group MG/EG indices come from the P_* constants EXPLICITLY: the
# layout is mostly even=mg/odd=eg but P_PASSED_* breaks that (both 784..787
# and 788..791 are even), so never derive them arithmetically.
_TERM_MG = np.array([
    E.P_DOUBLED_MG, E.P_ISOLATED_MG,
    E.P_PASSED_MG, E.P_PASSED_MG + 1, E.P_PASSED_MG + 2, E.P_PASSED_MG + 3,
    E.P_BLOCKED_MG,
    E.P_MOB_N_MG, E.P_MOB_B_MG, E.P_MOB_R_MG, E.P_MOB_Q_MG,
    E.P_SHELTER_NEAR_MG, E.P_SHELTER_FAR_MG, E.P_OPEN_MG, E.P_KDIST_MG,
    E.P_BISHOP_PAIR_MG,
], dtype=int)
_TERM_EG = np.array([
    E.P_DOUBLED_EG, E.P_ISOLATED_EG,
    E.P_PASSED_EG, E.P_PASSED_EG + 1, E.P_PASSED_EG + 2, E.P_PASSED_EG + 3,
    E.P_BLOCKED_EG,
    E.P_MOB_N_EG, E.P_MOB_B_EG, E.P_MOB_R_EG, E.P_MOB_Q_EG,
    E.P_SHELTER_NEAR_EG, E.P_SHELTER_FAR_EG, E.P_OPEN_EG, E.P_KDIST_EG,
    E.P_BISHOP_PAIR_EG,
], dtype=int)
MG_IDXS = np.r_[np.arange(0, 6), np.arange(12, 396), _TERM_MG]
EG_IDXS = np.r_[np.arange(6, 12), np.arange(396, 780), _TERM_EG]
assert len(MG_IDXS) + len(EG_IDXS) == N_P - 1          # everything but tempo
assert len(np.intersect1d(MG_IDXS, EG_IDXS)) == 0
# material (mg+eg) is FROZEN at the hand priors by default: the material
# constants and the PST mean are collinear (shifting all squares of a
# piece's table by c and material by -c leaves the eval unchanged), so an
# unanchored joint fit drifts to degenerate splits (e.g. queen 342cp).
# Anchoring material identifies the PST mean and keeps exchange values sane
# (standard Texel practice: tune tables around fixed piece values).
FREEZE_MAT = np.arange(0, 12)


# ---------------------------------------------------------------------------
# Feature extraction — EXACT mirror of engine/eval.py evaluate() (gate 1111)
# ---------------------------------------------------------------------------

def _sq64(sq: int) -> int:
    return ((sq >> 4) << 3) + (sq & 7)


def _mirror(b: int) -> int:
    x = b & 0xFFFFFFFFFFFFFFFF
    return (((x & 0x00000000000000FF) << 56) | ((x & 0x000000000000FF00) << 40)
            | ((x & 0x0000000000FF0000) << 24) | ((x & 0x00000000FF000000) << 8)
            | ((x & 0x000000FF00000000) >> 8) | ((x & 0x0000FF0000000000) >> 24)
            | ((x & 0x00FF000000000000) >> 40) | ((x & 0xFF00000000000000) >> 56))


def _popcount(x: int) -> int:
    return bin(x & 0xFFFFFFFFFFFFFFFF).count("1")


def feature_vector(st) -> tuple[np.ndarray, int, bool]:
    """(f int64[813], phase, forced_zero) mirroring evaluate()'s pass 1+2,
    king safety, bishop pair, tempo. forced_zero = the eval's insufficient-
    material early-return fires (score forced to 0) — such positions are
    dropped from training."""
    sqr = st['squares'][0]
    side = int(st['side'][0])
    f = np.zeros(N_P, dtype=np.int64)

    phase = 0
    wp = 0
    bp = 0
    mN = mB = mR = mQ = 0
    dbl = iso = blk = 0
    passed = [0, 0, 0, 0]
    sh_near = sh_far = opn = 0
    bishops = [0, 0]
    has_pawn = has_major = False
    mins = 0

    # ---- pass 1: material + PST + phase + mobility + bitboards ----
    for sq in range(128):
        if (sq & 0x88) != 0:
            continue
        pc = int(sqr[sq])
        if pc == 0:
            continue
        t = abs(pc)
        color = 1 if pc > 0 else 0
        s = _sq64(sq) if color == 1 else _sq64(sq) ^ 56
        sign = 1 if color == 1 else -1
        f[E.P_MAT_MG + t - 1] += sign
        f[E.P_MAT_EG + t - 1] += sign
        f[E.P_PST_MG + (t - 1) * 64 + s] += sign
        f[E.P_PST_EG + (t - 1) * 64 + s] += sign
        phase += int(E.PHASE_W[t])
        if t == B.PAWN:
            has_pawn = True
            b = 1 << _sq64(sq)
            if color == 1:
                wp |= b
            else:
                bp |= b
        elif t == B.ROOK or t == B.QUEEN:
            has_major = True
            if t == B.ROOK:
                for di in range(4):
                    for k in range(8):
                        to = int(E._ROOK_RAYS[sq, di, k])
                        if to < 0:
                            break
                        q = int(sqr[to])
                        if q == 0:
                            mR += sign
                        elif (q > 0) != (pc > 0):
                            mR += sign
                            break
                        else:
                            break
            else:
                for di in range(4):
                    for k in range(8):
                        to = int(E._RAYS[sq, di, k])
                        if to < 0:
                            break
                        q = int(sqr[to])
                        if q == 0:
                            mQ += sign
                        elif (q > 0) != (pc > 0):
                            mQ += sign
                            break
                        else:
                            break
                for di in range(4):
                    for k in range(8):
                        to = int(E._ROOK_RAYS[sq, di, k])
                        if to < 0:
                            break
                        q = int(sqr[to])
                        if q == 0:
                            mQ += sign
                        elif (q > 0) != (pc > 0):
                            mQ += sign
                            break
                        else:
                            break
        elif t == B.KNIGHT:
            mins += 1
            for d in range(8):
                to = sq + int(B._KNIGHT_DELTAS[d])
                if (to & 0x88) == 0:
                    q = int(sqr[to])
                    if q == 0 or (q > 0) != (pc > 0):
                        mN += sign
        elif t == B.BISHOP:
            mins += 1
            bishops[color] += 1
            for di in range(4):
                for k in range(8):
                    to = int(E._RAYS[sq, di, k])
                    if to < 0:
                        break
                    q = int(sqr[to])
                    if q == 0:
                        mB += sign
                    elif (q > 0) != (pc > 0):
                        mB += sign
                        break
                    else:
                        break
        elif t == B.KING:
            pass

    # ---- pass 2: pawn structure ----
    wpM = _mirror(wp)
    bpM = _mirror(bp)
    for sq in range(128):
        if (sq & 0x88) != 0:
            continue
        pc = int(sqr[sq])
        if pc == 0 or abs(pc) != B.PAWN:
            continue
        s = _sq64(sq)
        if pc > 0:
            b = 1 << s
            if (wp & int(E.ADJ_SQ[s])) == 0:
                iso += 1
            rk = s >> 3
            if (bp & int(E.PASSED_W[s])) == 0:
                if 3 <= rk <= 6:
                    if (bp & (b << 8)) != 0:
                        blk += 1
                    else:
                        passed[rk - 3] += 1
        else:
            sm = s ^ 56
            bm = 1 << sm
            if (bp & int(E.ADJ_SQ[s])) == 0:
                iso -= 1
            rk = sm >> 3
            if (wpM & int(E.PASSED_W[sm])) == 0:
                if 3 <= rk <= 6:
                    if (wpM & (bm << 8)) != 0:
                        blk -= 1
                    else:
                        passed[rk - 3] -= 1
    for ff in range(8):
        c = _popcount(wp & int(E.FILE_SQ[ff]))
        if c > 1:
            dbl += c - 1
        c = _popcount(bp & int(E.FILE_SQ[ff]))
        if c > 1:
            dbl -= c - 1

    # ---- king safety + tropism ----
    wks = _sq64(int(st['kingsq'][0][B.WHITE]))
    bks = _sq64(int(st['kingsq'][0][B.BLACK]))
    kdist = max(abs((wks & 7) - (bks & 7)), abs((wks >> 3) - (bks >> 3)))
    sh_near += _popcount(wp & int(E.SHELTER_NEAR[wks]))
    sh_far += _popcount(wp & int(E.SHELTER_FAR[wks]))
    if (wp & int(E.FILE_SQ[wks])) == 0:
        opn += 1
    bksm = bks ^ 56
    sh_near -= _popcount(bpM & int(E.SHELTER_NEAR[bksm]))
    sh_far -= _popcount(bpM & int(E.SHELTER_FAR[bksm]))
    if (bp & int(E.FILE_SQ[bks])) == 0:
        opn -= 1

    # ---- assemble feature groups ----
    f[E.P_DOUBLED_MG] = f[E.P_DOUBLED_EG] = dbl
    f[E.P_ISOLATED_MG] = f[E.P_ISOLATED_EG] = iso
    f[E.P_BLOCKED_MG] = f[E.P_BLOCKED_EG] = blk
    f[E.P_PASSED_MG:E.P_PASSED_MG + 4] = passed
    f[E.P_PASSED_EG:E.P_PASSED_EG + 4] = passed
    f[E.P_MOB_N_MG] = f[E.P_MOB_N_EG] = mN
    f[E.P_MOB_B_MG] = f[E.P_MOB_B_EG] = mB
    f[E.P_MOB_R_MG] = f[E.P_MOB_R_EG] = mR
    f[E.P_MOB_Q_MG] = f[E.P_MOB_Q_EG] = mQ
    f[E.P_SHELTER_NEAR_MG] = f[E.P_SHELTER_NEAR_EG] = sh_near
    f[E.P_SHELTER_FAR_MG] = f[E.P_SHELTER_FAR_EG] = sh_far
    f[E.P_OPEN_MG] = f[E.P_OPEN_EG] = opn
    f[E.P_KDIST_MG] = f[E.P_KDIST_EG] = kdist
    bpw = bishops[B.WHITE]
    bpb = bishops[B.BLACK]
    bp_val = (1 if bpw >= 2 else 0) - (1 if bpb >= 2 else 0)
    f[E.P_BISHOP_PAIR_MG] = f[E.P_BISHOP_PAIR_EG] = bp_val
    # Tempo is CONSTANT +1 in White-POV terms: evaluate() returns the
    # side-to-move value ±(SB+10) (black STM negates the whole thing
    # including tempo), so the White-POV score is SB + 10 regardless of
    # the side to move; engine == model(white) iff f[P_TEMPO] == +1.
    f[E.P_TEMPO] = 1

    forced_zero = (not has_pawn and not has_major and mins <= 1)
    return f, phase, forced_zero


def score_white(f: np.ndarray, phase: int, p: np.ndarray) -> int:
    """White-POV score, bit-exact with evaluate() (gate 1111): the eval's
    tempo sign convention is folded into f[P_TEMPO] (side to move)."""
    mg = int(f[MG_IDXS] @ p[MG_IDXS])
    eg = int(f[EG_IDXS] @ p[EG_IDXS])
    if phase > E.MAX_PHASE:
        phase = E.MAX_PHASE
    return (mg * phase + eg * (E.MAX_PHASE - phase)) // E.MAX_PHASE \
        + int(f[E.P_TEMPO]) * int(p[E.P_TEMPO])


