def load_data(path: Path, max_pos: int, seed: int):
    d = np.load(path, allow_pickle=True)
    fens = d["fens"].astype(str)
    results = d["results"].astype(np.float64)
    if max_pos and len(fens) > max_pos:
        rng = np.random.default_rng(seed)
        idx = rng.choice(len(fens), max_pos, replace=False)
        fens = fens[idx]
        results = results[idx]
    print(f"loaded {len(fens)} positions from {path}")
    return fens, results


def featurize(fens: np.ndarray):
    """CSR arrays (rows, cols, vals) + phases + keep-mask (drops
    insufficient-material positions whose eval score is forced 0)."""
    rows = []
    cols = []
    vals = []
    phases = np.zeros(len(fens), dtype=np.int32)
    drop = []
    t0 = time.monotonic()
    for i, fen in enumerate(fens):
        st = B.parse_fen(fen)
        f, phase, forced_zero = feature_vector(st)
        if forced_zero:
            drop.append(i)
            continue
        nz = np.nonzero(f)[0]
        rows.append(np.full(len(nz), i, dtype=np.int32))
        cols.append(nz.astype(np.int32))
        vals.append(f[nz].astype(np.int64))
        phases[i] = phase
    rows = np.concatenate(rows)
    cols = np.concatenate(cols)
    vals = np.concatenate(vals)
    keep = np.setdiff1d(np.arange(len(fens)), np.array(drop))
    print(f"featurized {len(fens)} positions in {time.monotonic() - t0:.1f}s "
          f"({len(rows)} nnz, {len(drop)} insufficient-material dropped)")
    return rows, cols, vals, phases[keep], keep


# ---------------------------------------------------------------------------
# IRWLS on the logistic loss (chunked, numpy-only)
# ---------------------------------------------------------------------------

def _blocks(n: int, size: int = 2048):
    for i0 in range(0, n, size):
        yield i0, min(i0 + size, n)


def fit_irwls(rows, cols, vals, phases, y, init, iters=8, lam=1e-3,
              block=2048, seed=7, freeze=FREEZE_MAT):
    p = np.array(init, dtype=np.float64)
    n = len(y)
    free = np.setdiff1d(np.arange(N_P), freeze) if freeze is not None \
        else np.arange(N_P)
    rng = np.random.default_rng(seed)
    val_idx = rng.choice(n, max(1, n // 20), replace=False)
    tr_idx = np.setdiff1d(np.arange(n), val_idx)
    s_all = np.zeros(n)
    dln = np.log(10.0) / 400.0

    def one_block(i0, i1, pv):
        """Dense design matrix block (n_block x N_P) + engine-exact scores."""
        m = (rows >= i0) & (rows < i1)
        X = np.zeros((i1 - i0, N_P))
        np.add.at(X, (rows[m] - i0, cols[m]), vals[m])
        ph = np.minimum(phases[i0:i1], E.MAX_PHASE).astype(np.float64)
        mg = X[:, MG_IDXS] @ pv[MG_IDXS]
        eg = X[:, EG_IDXS] @ pv[EG_IDXS]
        s = (np.floor((mg * ph + eg * (E.MAX_PHASE - ph)) / E.MAX_PHASE)
             + X[:, E.P_TEMPO] * pv[E.P_TEMPO])
        return X, s, ph

    def full_pass(pv):
        for i0, i1 in _blocks(n, block):
            _, s, _ = one_block(i0, i1, pv)
            s_all[i0:i1] = s

    def losses():
        sig = 1.0 / (1.0 + 10.0 ** (-s_all / 400.0))
        return (float(np.mean((sig[tr_idx] - y[tr_idx]) ** 2)),
                float(np.mean((sig[val_idx] - y[val_idx]) ** 2)))

    full_pass(p)
    tr_l, va_l = losses()
    print(f"iter  0 train {tr_l:.6f} val {va_l:.6f}")

    for it in range(1, iters + 1):
        sig_all = 1.0 / (1.0 + 10.0 ** (-s_all / 400.0))
        resid = sig_all - y
        G = np.zeros((N_P, N_P))
        b = np.zeros(N_P)
        for i0, i1 in _blocks(n, block):
            X, s, ph = one_block(i0, i1, p)
            sig = sig_all[i0:i1]
            sd = dln * sig * (1.0 - sig)
            w = sd ** 2
            z = s + resid[i0:i1] / (sd + 1e-12)
            rw = w * (z - s)
            Xs = X.copy()
            Xs[:, EG_IDXS] *= (E.MAX_PHASE - ph)[:, None] / E.MAX_PHASE
            Xs[:, MG_IDXS] *= ph[:, None] / E.MAX_PHASE
            G += Xs.T @ (Xs * w[:, None])
            b += Xs.T @ rw
        G += np.eye(N_P) * lam
        Gf = G[free][:, free]
        bf = b[free]
        try:
            delta_f = np.linalg.solve(Gf, bf)
        except np.linalg.LinAlgError:
            delta_f = np.linalg.lstsq(Gf, bf, rcond=None)[0]
        delta = np.zeros(N_P)
        delta[free] = delta_f

        step = 1.0
        while step > 1e-4:
            cand = p - step * delta
            full_pass(cand)
            tr_c, va_c = losses()
            if tr_c <= tr_l + 1e-9:
                p = cand
                tr_l, va_l = tr_c, va_c
                break
            step *= 0.5
        if step <= 1e-4:
            raise RuntimeError("IRWLS step failed to reduce training loss")
        print(f"iter {it:2d} train {tr_l:.6f} val {va_l:.6f} "
              f"step {step:.2f} max|dp| {np.max(np.abs(delta * step)):.1f}")
    return p


