def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--data", required=True)
    ap.add_argument("--max-pos", type=int, default=0)
    ap.add_argument("--iters", type=int, default=8)
    ap.add_argument("--lam", type=float, default=1e-3)
    ap.add_argument("--init", default="tuned",
                    help="hand|tuned start point (tuned==hand pre-tuning)")
    ap.add_argument("--no-patch", action="store_true")
    ap.add_argument("--seed", type=int, default=7)
    args = ap.parse_args()

    np.set_printoptions(linewidth=160)
    init = (np.array(E.HAND_PARAMS, dtype=np.float64) if args.init == "hand"
            else np.array(E.TUNED_PARAMS, dtype=np.float64))
    print(f"init: {args.init} (N_PARAMS={N_P})")

    # 1. structural validation: feature extraction vs the jitted engine
    hand = np.array(E.HAND_PARAMS, dtype=np.float64)
    check_parity(hand, 60)
    maxg = check_gradient(hand, _parity_fens())
    print(f"gradient finite-diff |max diff|: {maxg:.2e}")
    if maxg > 1.0:
        print("WARNING: analytic gradient deviates (floor noise is <1cp; "
              "this should be tiny)")

    # 2. load + featurize
    fens, results = load_data(Path(args.data), args.max_pos, args.seed)
    rows, cols, vals, phases, keep = featurize(fens)
    y = results[keep]
    print(f"fitting on {len(y)} positions, {N_P} params, "
          f"sparsity {len(rows) / (len(y) * N_P):.4f}")

    # 3. IRWLS
    p = fit_irwls(rows, cols, vals, phases, y, init,
                  iters=args.iters, lam=args.lam, seed=args.seed)

    # 4. report
    pint = np.rint(p).astype(np.int64)
    pinit = np.rint(init).astype(np.int64)
    print("\n== fitted params (rounded to int) ==")
    print("material mg :", pint[E.P_MAT_MG:E.P_MAT_MG + 6])
    print("material eg :", pint[E.P_MAT_EG:E.P_MAT_EG + 6])
    print("passed mg   :", pint[E.P_PASSED_MG:E.P_PASSED_MG + 4])
    print("passed eg   :", pint[E.P_PASSED_EG:E.P_PASSED_EG + 4])
    print("doub/iso/blk mg:", pint[[E.P_DOUBLED_MG, E.P_ISOLATED_MG,
                                    E.P_BLOCKED_MG]])
    print("mob N/B/R/Q mg:", pint[[E.P_MOB_N_MG, E.P_MOB_B_MG,
                                   E.P_MOB_R_MG, E.P_MOB_Q_MG]])
    print("shelter n/f mg, open mg:",
          pint[[E.P_SHELTER_NEAR_MG, E.P_SHELTER_FAR_MG, E.P_OPEN_MG]])
    print("kdist mg/eg :", pint[[E.P_KDIST_MG, E.P_KDIST_EG]])
    print("bishop pr mg/eg:", pint[[E.P_BISHOP_PAIR_MG, E.P_BISHOP_PAIR_EG]])
    print("tempo       :", pint[E.P_TEMPO])
    chg = np.abs(pint - pinit)
    print(f"max |delta| vs init: {chg.max()}  mean: {chg.mean():.1f}  "
          f"params changed: {(chg > 2).sum()}/{N_P}")

    # 5. provenance + optional patch + verification
    out_npy = Path(args.data).parent / \
        f"tuned_params_{time.strftime('%Y%m%d_%H%M%S')}.npy"
    np.save(out_npy, pint)
    print(f"saved weights: {out_npy}")
    if not args.no_patch:
        target = patch_eval_py(pint)
        print(f"patched TUNED_PARAMS into {target}")
        env = dict(os.environ)
        env["PYTHONPATH"] = str(_HERE.parent)
        r = subprocess.run([sys.executable,
                            str(_HERE.parent / "engine" / "eval.py")],
                           capture_output=True, text=True, env=env,
                           cwd=str(_HERE.parent))
        print(r.stdout.strip() or r.stderr.strip())
        if r.returncode != 0:
            return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())